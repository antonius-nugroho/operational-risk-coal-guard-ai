export function mapRawFailuresToLossEvents(rawList: RawFailureData[]): LossEvent[] {
  return rawList.map((f, idx) => ({
    id: f.id || `fail-${idx}`,
    date: f.timestamp_start.split(' ').slice(0, 3).join(' '),
    plantId: 'plant-tarahan',
    unit: f.unit_no,
    category: f.category as LossCategory,
    forcedOutageHours: Math.round(f.failure_duration_hours * 10) / 10,
    mwhLost: Math.round(f.loss_output_mwh),
    financialLossUSD: Math.round(f.financialLossUSD),
    rootCause: `${f.root_cause_failure_analysis} [Status: ${f.unit_status}] - Asset: ${f.asset_number || 'Plant Subsystem'}`,
    detectedBy: f.detectedBy,
    severity: f.severity,
    preventableWithML: f.preventableWithML,
    mitigationActionTaken: f.mitigation || 'Equipment inspection and corrective maintenance applied.'
  }));
}
